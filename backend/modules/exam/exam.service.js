export const getReport = async (exam_id) => {
  const [exam, marks] = await Promise.all([
    prisma.exam.findUnique({ where:{ id:exam_id }, include:{ schedule:{ include:{ subject:true } } } }),
    prisma.examMark.findMany({ where:{ exam_id }, include:{ student:{ select:{ id:true, name:true, roll_no:true, section:{ select:{ name:true } } } }, subject:{ select:{ id:true, name:true, code:true } } } }),
  ]);
  const bySubject = {};
  for (const m of marks) {
    const key = m.subject_id;
    if (!bySubject[key]) bySubject[key] = { subject:m.subject, entries:[], total:0, pass:0, absent:0, avg:0 };
    bySubject[key].entries.push(m);
    if (m.is_absent) bySubject[key].absent++;
    else {
      bySubject[key].total++;
      const pct = m.max_marks > 0 ? m.marks_obtained/m.max_marks*100 : 0;
      if (pct >= 40) bySubject[key].pass++;
    }
  }
  for (const k of Object.keys(bySubject)) {
    const s = bySubject[k];
    const present = s.entries.filter(e => !e.is_absent);
    s.avg = present.length ? +(present.reduce((sum,e) => sum+e.marks_obtained, 0)/present.length).toFixed(1) : 0;
    s.pass_pct = s.total > 0 ? +(s.pass/s.total*100).toFixed(1) : 0;
  }
  return { exam, subjectReport: Object.values(bySubject), total_marks: marks.length, total_absent: marks.filter(m=>m.is_absent).length };
};
