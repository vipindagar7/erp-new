// ── HALL TICKETS ──────────────────────────────────────────────
export const generateHallTickets = async (exam_id, student_ids = []) => {
  if (!student_ids.length) {
    const seatings = await prisma.examSeating.findMany({ where:{ exam_id }, select:{ student_id:true } });
    student_ids = [...new Set(seatings.map(s => s.student_id))];
  }

  const results = [];
  for (const student_id of student_ids) {
    const ticket_no = `HT-${exam_id.slice(-4).toUpperCase()}-${student_id.slice(-6).toUpperCase()}`;
    const r = await prisma.hallTicket.upsert({
      where:  { exam_id_student_id:{ exam_id, student_id } },
      update: { ticket_no, is_valid:true, generated_at:new Date() },
      create: { exam_id, student_id, ticket_no, is_valid:true },
    });
    results.push(r);
  }
  return { generated: results.length };
};

export const getHallTicketData = async (exam_id, student_id) => {
  const [student, exam, seatings, ticket] = await Promise.all([
    prisma.student.findUnique({ where:{ id:student_id }, include:{ branch:true, section:true } }),
    prisma.exam.findUnique({ where:{ id:exam_id }, include:{ schedule:{ include:{ subject:true } } } }),
    prisma.examSeating.findMany({ where:{ exam_id, student_id }, include:{ exam_room:{ include:{ room:true } } } }),
    prisma.hallTicket.findUnique({ where:{ exam_id_student_id:{ exam_id, student_id } } }),
  ]);
  return { student, exam, seatings, ticket };
};

// ── MARKS ─────────────────────────────────────────────────────
export const enterMarks = async (exam_id, subject_id, marks_data, entered_by) => {
  const results = [];
  for (const m of marks_data) {
    const r = await prisma.examMark.upsert({
      where:  { exam_id_student_id_subject_id:{ exam_id, student_id:m.student_id, subject_id } },
      update: { marks_obtained:m.marks, is_absent:m.is_absent||false, remarks:m.remarks, entered_by },
      create: { exam_id, student_id:m.student_id, subject_id, exam_type:m.exam_type, marks_obtained:m.marks||0, max_marks:m.max_marks||100, is_absent:m.is_absent||false, remarks:m.remarks, entered_by },
    });
    results.push(r);
  }
  return results;
};

