// Auto-generate datesheet from academic calendar
export const autoGenerateDatesheet = async (exam_id, { start_date, subjects_per_day=1, skip_holidays=true, session_id }) => {
  const exam     = await prisma.exam.findUnique({ where:{ id:exam_id }, include:{ schedule:{ include:{ subject:true } } } });
  if (!exam) throw nf();
  
  const holidays = skip_holidays ? await prisma.academicCalendarEvent.findMany({
    where: { session_id: session_id||exam.session_id, is_holiday:true, deleted_at:null },
    select: { start_date:true, end_date:true },
  }) : [];

  const isHoliday = (date) => holidays.some(h => date >= h.start_date && date <= h.end_date);

  let current = new Date(start_date);
  const entries = [];

  for (const sch of exam.schedule) {
    while (isHoliday(current) || current.getDay() === 0) {
      current.setDate(current.getDate() + 1);
    }
    entries.push({ ...sch, suggested_date: new Date(current) });
    current.setDate(current.getDate() + 1);
  }

  return entries;
};

// ── SEATING ───────────────────────────────────────────────────
export const autoGenerateSeating = async (exam_id, exam_date) => {
  // Get all students for this exam (from sections/branches in schedule)
  const exam = await prisma.exam.findUnique({ where:{ id:exam_id }, include:{ schedule:true, rooms:{ where:{ exam_date: new Date(exam_date) }, include:{ room:true } } } });
  if (!exam) throw nf();

  const section_ids = [...new Set(exam.schedule.flatMap(s => s.section_ids))];
  const students    = await prisma.student.findMany({
    where: { section_id:{ in:section_ids }, status:"ACTIVE" },
    select: { id:true, roll_no:true, name:true },
    orderBy: { roll_no:"asc" },
  });

  // Shuffle branches (mix different sections)
  const shuffled = students.sort(() => Math.random() - 0.5);

  const rooms   = exam.rooms;
  let roomIdx   = 0, seatNo = 1;
  const seatings = [];

  for (const student of shuffled) {
    if (roomIdx >= rooms.length) break;
    const room = rooms[roomIdx];
    
    seatings.push({
      exam_id, exam_room_id: room.id, student_id: student.id,
      roll_no: student.roll_no, seat_no: `${String.fromCharCode(65+roomIdx)}${seatNo}`,
      exam_date: new Date(exam_date),
    });

    seatNo++;
    if (seatNo > room.capacity) { roomIdx++; seatNo = 1; }
  }

  // Delete existing auto seatings
  await prisma.examSeating.deleteMany({ where: { exam_id, exam_date:new Date(exam_date), is_manual:false } });

  // Create new
  await prisma.examSeating.createMany({ data: seatings, skipDuplicates:true });
  return { generated: seatings.length, rooms: rooms.length };
};

