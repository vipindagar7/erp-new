const nf = (msg="Exam not found") => Object.assign(new Error(msg), { status:404 });

// ── EXAM CRUD ─────────────────────────────────────────────────
export const listExams = async ({ session_id, exam_type, status, dept_id, page=1, limit=20 }) => {
  const where = { deleted_at: null };
  if (session_id)  where.session_id = session_id;
  if (exam_type)   where.exam_type  = exam_type;
  if (status)      where.status     = status;
  if (dept_id)     where.dept_ids   = { has: dept_id };
  const skip = (page-1)*limit;
  const [items, total] = await Promise.all([
    prisma.exam.findMany({ where, skip, take:+limit, include:{ _count:{ select:{ schedule:true, seatings:true, hallTickets:true } } }, orderBy:{ start_date:"asc" } }),
    prisma.exam.count({ where }),
  ]);
  return { items, total, page:+page, limit:+limit };
};

export const getExam = async (id) => {
  const e = await prisma.exam.findUnique({ where:{ id }, include:{ schedule:{ include:{ subject:true } }, rooms:{ include:{ room:true } }, hallTickets:{ select:{ id:true, student_id:true } } } });
  if (!e) throw nf();
  return e;
};

